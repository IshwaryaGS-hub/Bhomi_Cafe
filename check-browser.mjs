import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
mkdirSync('test-results', { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const errors = [];
const failedRequests = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => { if (response.status() >= 400 && response.url().includes('127.0.0.1')) failedRequests.push(response.url()); });
try {
  await page.goto('http://127.0.0.1:5174', { waitUntil: 'domcontentloaded' });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForFunction(() => document.querySelector('.hero video')?.readyState >= 2, null, { timeout: 60000 });
  assert.match(await page.title(), /பூமி/);
  assert.ok((await page.locator('.brand').innerText()).includes('பூமி'));
  assert.ok(!/Mitti|mitti|Ã|Â|â€|�/.test(await page.locator('body').innerText()), 'No old brand or corrupted text');
  const time = await page.locator('.hero video').evaluate(video => video.currentTime);
  await page.waitForTimeout(1200);
  assert.ok(await page.locator('.hero video').evaluate((video, before) => video.currentTime > before, time), 'Hero video plays');
  await page.getByRole('button', { name: 'Pause motion', exact: true }).click();
  assert.equal(await page.locator('.hero video').evaluate(video => video.paused), true);
  await page.screenshot({ path: 'test-results/desktop-hero.png' });
  await page.getByRole('button', { name: 'Watch the journey', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('button', { name: 'Next chapter', exact: true }).click();
  assert.ok((await page.getByRole('dialog').innerText()).includes('Care you can feel'));
  await page.getByRole('button', { name: 'Play The pour chapter', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.film-screen video')?.readyState >= 2, null, { timeout: 30000 });
  await page.getByRole('button', { name: 'Pause film', exact: true }).click();
  assert.equal(await page.locator('.film-screen video').evaluate(video => video.paused), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.getByRole('button', { name: /Coffee & kaapi/ }).click();
  assert.equal(await page.locator('.drink-card').count(), 8);
  await page.locator('.drink-card').first().click();
  assert.ok((await page.getByRole('dialog').innerText()).includes('₹110'));
  await page.keyboard.press('Shift+Tab');
  assert.ok(await page.getByRole('dialog').evaluate(dialog => dialog.contains(document.activeElement)), 'Focus stays inside dialog');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Show favourites', exact: true }).click();
  assert.equal(await page.locator('.drink-card').count(), 4);
  await page.getByRole('button', { name: 'Explore all coffees', exact: true }).click();
  assert.equal(await page.locator('.drink-card').count(), 8);
  await page.getByRole('button', { name: /Tea & chai/ }).click();
  assert.equal(await page.locator('.drink-card').first().evaluate(el => getComputedStyle(el).opacity), '1', 'Cards stay visible when motion is paused');
  await page.evaluate(() => window.scrollTo({ top: document.querySelector('#menu').offsetTop + 40, behavior: 'instant' }));
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'test-results/desktop-menu.png' });
  assert.equal(await page.locator('.drink-card').count(), 8);
  await page.locator('.drink-card').last().scrollIntoViewIfNeeded();
  await page.waitForTimeout(500);
  const missing = await page.locator('img').evaluateAll(imgs => imgs.filter(img => img.complete && img.naturalWidth === 0).map(img => img.src));
  assert.deepEqual(missing, [], 'No failed images');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://127.0.0.1:5174', { waitUntil: 'domcontentloaded' });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(1000);
  await page.screenshot({ path: 'test-results/mobile-hero.png' });
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
  await page.locator('nav').getByRole('link', { name: 'Our menu', exact: true }).click();
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'test-results/mobile-menu.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'No mobile horizontal overflow');
  await page.locator('#journey').scrollIntoViewIfNeeded();
  await page.locator('.chapter-tabs').getByRole('button', { name: /The craft/ }).click();
  await page.waitForFunction(() => document.querySelector('.chapter-frame video')?.readyState >= 2, null, { timeout: 30000 });
  await page.screenshot({ path: 'test-results/mobile-journey.png' });
  const reduced = await browser.newPage({ reducedMotion: 'reduce', viewport: { width: 390, height: 844 } });
  await reduced.goto('http://127.0.0.1:5174', { waitUntil: 'domcontentloaded' });
  assert.equal(await reduced.getByRole('button', { name: 'Resume motion', exact: true }).count(), 1);
  assert.equal(await reduced.locator('.hero video').evaluate(video => video.paused), true);
  await reduced.close();
  assert.deepEqual(errors, []);
  assert.deepEqual(failedRequests, []);
  console.log(JSON.stringify({ success: true, errors, failedRequests, checked: ['Tamil brand', 'clean UTF-8', 'rupee formatting', 'real video playback', 'motion pause', 'film chapters', 'film pause', 'menu categories', 'expanded menus', 'dialog focus', 'mobile navigation', 'mobile overflow', 'reduced motion'] }));
} finally { await browser.close(); }
