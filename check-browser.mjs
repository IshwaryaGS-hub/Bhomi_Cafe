import { chromium } from '@playwright/test';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173',{waitUntil:'networkidle'});
await page.screenshot({path:'desktop-preview.png',fullPage:false});
await page.getByRole('button',{name:'Coffee',exact:true}).click();
await page.getByRole('button',{name:/South Indian Filter Coffee/}).click();
await page.getByRole('dialog').waitFor();
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Play the journey'}).click();
await page.waitForTimeout(4600);
await page.getByRole('button',{name:'Pause the journey'}).click();
const missing=await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||i.naturalWidth===0).map(i=>i.src));
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:5173',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Toggle navigation'}).click();
await page.locator('nav').getByRole('link',{name:'The menu'}).click();
await page.getByRole('button',{name:'Tea & chai'}).click();
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await page.screenshot({path:'mobile-preview.png',fullPage:true});
await browser.close();
console.log(JSON.stringify({errors,missing,mobileOverflow:overflow,verified:['menu switching','cup dialog','escape dismissal','journey play/pause','mobile navigation','image loading']}));
if(errors.length||missing.length||overflow)process.exit(1);
